#!/usr/bin/env bash
# Writes Formula/devcat-cli.rb and Casks/devcat.rb for the latest DevCat release, from its
# SHA256SUMS.txt. Run by .github/workflows/update.yml; `./update.sh v0.7.0` for one version.
# SUMS_FILE=<file> uses a local checksum list instead of downloading it (testing).
set -euo pipefail
REPO=devcathq/DevCat
cd "$(dirname "$0")"

tag=${1:-$(curl -fsSL "https://api.github.com/repos/$REPO/releases/latest" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -1)}
[ -n "$tag" ] || { echo "no release found" >&2; exit 1; }
v=${tag#v}
sums=$(if [ -n "${SUMS_FILE:-}" ]; then cat "$SUMS_FILE"; else curl -fsSL "https://github.com/$REPO/releases/download/$tag/SHA256SUMS.txt"; fi)
sum() {
  local s
  s=$(printf '%s\n' "$sums" | awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }')
  [ -n "$s" ] || { echo "$tag has no $1" >&2; exit 1; }
  echo "$s"
}
url="https://github.com/$REPO/releases/download/v#{version}"

mkdir -p Formula Casks
cat > Formula/devcat-cli.rb <<RUBY
# Generated by update.sh: don't edit by hand.
class DevcatCli < Formula
  desc "DevCat without a window: share this computer with DevCat Mobile and browsers"
  homepage "https://github.com/$REPO"
  version "$v"

  on_macos do
    on_arm do
      url "$url/devcat-cli-aarch64-apple-darwin.tar.gz"
      sha256 "$(sum devcat-cli-aarch64-apple-darwin.tar.gz)"
    end
    on_intel do
      url "$url/devcat-cli-x86_64-apple-darwin.tar.gz"
      sha256 "$(sum devcat-cli-x86_64-apple-darwin.tar.gz)"
    end
  end

  on_linux do
    on_arm do
      url "$url/devcat-cli-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum devcat-cli-aarch64-unknown-linux-gnu.tar.gz)"
    end
    on_intel do
      url "$url/devcat-cli-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum devcat-cli-x86_64-unknown-linux-gnu.tar.gz)"
    end
  end

  def install
    bin.install "devcat"
  end

  def caveats
    <<~EOS
      Start sharing this computer with DevCat Mobile and phone browsers:
        devcat serve
      It uses the same data folder (connections, paired phones) as the DevCat app.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/devcat version")
  end
end
RUBY

cat > Casks/devcat.rb <<RUBY
# Generated by update.sh: don't edit by hand.
cask "devcat" do
  arch arm: "aarch64", intel: "x64"

  version "$v"
  sha256 arm:   "$(sum "DevCat_${v}_aarch64.dmg")",
         intel: "$(sum "DevCat_${v}_x64.dmg")"

  url "https://github.com/$REPO/releases/download/v#{version}/DevCat_#{version}_#{arch}.dmg"
  name "DevCat"
  desc "Developer workbench: AI coding agents, Git, databases, Kubernetes and VPNs"
  homepage "https://github.com/$REPO"

  auto_updates true
  depends_on :macos

  app "DevCat.app"

  zap trash: [
    "~/Library/Application Support/dev.devcat.app",
    "~/Library/Caches/dev.devcat.app",
    "~/Library/WebKit/dev.devcat.app",
  ]

  caveats <<~EOS
    DevCat isn't notarized by Apple yet. The first time, open it from Applications; when macOS
    says it can't verify the developer, click Open Anyway in System Settings → Privacy & Security.
  EOS
end
RUBY
echo "DevCat $v"
